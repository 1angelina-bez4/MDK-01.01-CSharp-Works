using System.Threading.Tasks;

namespace var4
{
    /// <summary>
    /// Вычисляет периметр равностороннего треугольника.
    /// </summary>
    public class TriangleCalculator
    {
        /// <summary>
        /// Находим пириметр равностороннего треугольника
        /// </summary>
        /// <param name="a">Сторона треугольника с консоли</param>
        /// <returns>возращаем периметр P=3*а</returns>
        public double TriangleP(double a)
        {
            return 3*a;
        }
    }
